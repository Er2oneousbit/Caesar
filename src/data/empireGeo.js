/**
 * empireGeo.js
 * ----------------------------------------------------------------------------
 * The geography under the empire map (ui/empireMap.js): the Mediterranean
 * world from the Atlantic to Syria, written down as longitude and latitude
 * from general geographic knowledge (coasts, islands, rivers, mountains) and
 * projected onto the map's 100 x 60 "map unit" space. Drawn for this game;
 * no map from any game or atlas was traced.
 *
 * Projection: equirectangular, longitude 10 W to 37 E across the width and
 * latitude 48 N to 26.5 N down the height. One degree of longitude is about
 * 0.76 of a degree of latitude on the map, which is the true ratio near 40 N
 * (Naples), so the middle of the sea keeps its real shape.
 *
 * Everything here is pure data and arithmetic (no canvas): the tests use
 * `isLand` to check that every partner sits on land, every port by the
 * water, every caravan road over land and every sea lane over water.
 *
 * Detail is a few points per 100 km: enough for the boot, the heel and the
 * toe, the three fingers of the Peloponnese and the Nile delta to read at
 * the size the map is drawn, no more.
 * ----------------------------------------------------------------------------
 */

export const MAP_W = 100;
export const MAP_H = 60;

/** The map's edges in degrees. */
export const LON_WEST = -10;
export const LON_EAST = 37;
export const LAT_NORTH = 48;
export const LAT_SOUTH = 26.5;

/** [lon, lat] in degrees (east and north positive) to [x, y] in map units (y grows south). */
export function project([lon, lat]) {
  return [
    ((lon - LON_WEST) * MAP_W) / (LON_EAST - LON_WEST),
    ((LAT_NORTH - lat) * MAP_H) / (LAT_NORTH - LAT_SOUTH),
  ];
}

const projectAll = (pts) => Object.freeze(pts.map((p) => Object.freeze(project(p))));

/** A place on the map from its longitude and latitude: `at(12.48, 41.9)` is Rome. */
export function at(lon, lat) {
  return Object.freeze(project([lon, lat]));
}

