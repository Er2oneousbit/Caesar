/** Is a point (map units) inside a polygon? Even-odd ray casting. */
export function inPolygon([x, y], poly) {
  let inside = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Is this point of the map (map units) land? Islands are land on the sea; gulfs and lakes water on the land. */
export function isLand(p) {
  if (WATERS.some((w) => inPolygon(p, w))) return false;
  if (!inPolygon(p, SEA)) return true;
  return ISLANDS.some((isl) => inPolygon(p, isl));
}
